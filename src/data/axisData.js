export function getSpot(id) {
  return axisSpots.find((spot) => spot.id === Number(id));
}

export function getRoutePositions(ids) {
  return ids.map(getSpot).filter(Boolean).map((spot) => spot.position);
}

export function getRouteNames(ids) {
  return ids.map(getSpot).filter(Boolean).map((spot) => spot.name).join(' → ');
}
